def plot_fel(all_data: dict[tuple[str, str], pd.DataFrame]) -> None:
    r_const = 0.00831446261815324
    temp = 300.0
    fig, axes = plt.subplots(2, 3, figsize=(8.4, 5.1))
    axes = axes.ravel()
    fel_maps = []
    vmax_values = []
    for sys_info in SYSTEMS:
        rmsd = all_data[(sys_info.pair_id, "protein_rmsd")]
        rg = all_data[(sys_info.pair_id, "rg")]
        merged = pd.merge_asof(
            rmsd.sort_values("x"),
            rg.sort_values("x"),
            on="x",
            direction="nearest",
            tolerance=0.006,
            suffixes=("_rmsd", "_rg"),
        ).dropna()
        x = merged["value_rmsd"].to_numpy(dtype=float)
        y = merged["value_rg"].to_numpy(dtype=float)
        hist, xedges, yedges = np.histogram2d(x, y, bins=45)
        prob = hist / np.nansum(hist)
        with np.errstate(divide="ignore", invalid="ignore"):
            energy = -r_const * temp * np.log(prob)
        energy[np.isfinite(energy)] -= np.nanmin(energy[np.isfinite(energy)])
        energy[~np.isfinite(energy)] = np.nan
        fel_maps.append((sys_info, xedges, yedges, energy))
        vmax_values.append(np.nanpercentile(energy, 98))

    vmax = float(np.nanmax(vmax_values))
    last_mesh = None
    for ax, (sys_info, xedges, yedges, energy) in zip(axes[:-1], fel_maps):
        last_mesh = ax.pcolormesh(xedges, yedges, energy.T, cmap="viridis", shading="auto", vmin=0, vmax=vmax)
        ax.set_title(sys_info.label, pad=5)
        ax.set_xlabel("Protein RMSD (nm)")
        ax.set_ylabel("Rg (nm)")
        clean_axis(ax)
        ax.grid(False)
    for ax in axes[len(fel_maps):-1]:
        ax.axis("off")
    cax = axes[-1]
    cax.clear()
    if last_mesh is not None:
        cbar = fig.colorbar(last_mesh, cax=cax)
        cbar.set_label("Free energy (kJ/mol)")
    fig.subplots_adjust(wspace=0.42, hspace=0.42)
    save_figure(fig, OUT / "04_figures" / "04_fel_rmsd_rg_2d")
    plt.close(fig)


def make_tables(all_data: dict[tuple[str, str], pd.DataFrame]) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    summaries = []
    blocks = []
    for sys_info in SYSTEMS:
        for metric, meta in METRICS.items():
            data = all_data[(sys_info.pair_id, metric)]
            if meta["kind"] != "time":
                continue
            summary, block_rows = full_and_block_stats(sys_info, metric, data)
            summaries.append(summary)
            blocks.extend(block_rows)

    rmsf_rows = []
    for sys_info in SYSTEMS:
        data = all_data[(sys_info.pair_id, "rmsf")]
        top = data.sort_values("value", ascending=False).head(10)
        for _, row in top.iterrows():
            rmsf_rows.append(
                {
                    "pair_id": sys_info.pair_id,
                    "system": sys_info.label,
                    "protein": sys_info.protein,
                    "ligand": sys_info.ligand,
                    "residue_index": int(row["x"]),
                    "rmsf_nm": float(row["value"]),
                }
            )

    return pd.DataFrame(summaries), pd.DataFrame(blocks), pd.DataFrame(rmsf_rows)


def copy_raw_timeseries(all_data: dict[tuple[str, str], pd.DataFrame]) -> None:
    raw_dir = OUT / "02_tidy_timeseries"
    raw_dir.mkdir(parents=True, exist_ok=True)
    for sys_info in SYSTEMS:
        for metric in METRICS:
            data = all_data[(sys_info.pair_id, metric)].copy()
            data.insert(0, "metric", metric)
            data.insert(0, "system", sys_info.label)
            data.insert(0, "pair_id", sys_info.pair_id)
            data.to_csv(raw_dir / f"{sys_info.pair_id}__{metric}.csv", index=False)


def write_report(summary: pd.DataFrame, blocks: pd.DataFrame) -> None:
    lines = [
        "# MD core analysis report",
        "",
        "## Analysis scope",
        "",
        f"- Systems: {len(SYSTEMS)} completed 100 ns protein-ligand MD simulations.",
        "- Trajectories were centered on Protein_UNL, compacted with periodic boundary handling, and fitted to the protein backbone.",
        "- Core metrics: complex RMSD, protein backbone RMSD, ligand RMSD after backbone fitting, C-alpha RMSF, protein Rg, protein SASA, and strict protein-ligand hydrogen bonds.",
        "- Hydrogen bonds used `gmx hbond-legacy` with donor-acceptor distance <= 0.35 nm and angle cutoff 30 degrees. Polar contacts were not used as a substitute.",
        "- Statistics were summarized for the whole 0-100 ns trajectory and for the last 20 ns using four 5 ns block means.",
        f"- 95% confidence intervals were calculated from block means. Cross-system p-values were not calculated because the {len(SYSTEMS)} complexes are different systems rather than independent replicates of one condition.",
        "",
        "## Output files",
        "",
        "- Raw GROMACS outputs: each system's `03_analysis` folder.",
        "- Tidy CSV time series: `12_md_candidates/06_md_analysis/02_tidy_timeseries`.",
        "- Summary tables: `12_md_candidates/06_md_analysis/03_tables`.",
        "- Figures: `12_md_candidates/06_md_analysis/04_figures`.",
        "",
        "## Quick final-20-ns summary",
        "",
    ]
    pivot = summary.pivot_table(
        index="system",
        columns="metric",
        values="final_80_100ns_block_mean",
        aggfunc="first",
    )
    lines.append("```")
    lines.append(pivot.round(3).to_string())
    lines.append("```")
    lines.append("")
    (OUT / "05_reports").mkdir(parents=True, exist_ok=True)
    (OUT / "05_reports" / "md_core_analysis_report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    configure_style()
    for sub in ["02_tidy_timeseries", "03_tables", "04_figures", "05_reports"]:
        (OUT / sub).mkdir(parents=True, exist_ok=True)

    all_data: dict[tuple[str, str], pd.DataFrame] = {}
    for sys_info in SYSTEMS:
        for metric in METRICS:
            all_data[(sys_info.pair_id, metric)] = metric_series(sys_info, metric)

    summary, blocks, rmsf_top = make_tables(all_data)
    copy_raw_timeseries(all_data)

    tables_dir = OUT / "03_tables"
    summary.to_csv(tables_dir / "md_core_summary_statistics.csv", index=False)
    blocks.to_csv(tables_dir / "md_core_80_100ns_block_statistics.csv", index=False)
    rmsf_top.to_csv(tables_dir / "md_rmsf_top10_residues.csv", index=False)
    with pd.ExcelWriter(tables_dir / "md_core_analysis_tables.xlsx", engine="openpyxl") as writer:
        summary.to_excel(writer, sheet_name="summary_statistics", index=False)
        blocks.to_excel(writer, sheet_name="80_100ns_blocks", index=False)
        rmsf_top.to_excel(writer, sheet_name="rmsf_top10", index=False)

    plot_core_timeseries(all_data)
    plot_individual_timeseries(all_data)
    plot_rmsf(all_data)
    plot_summary_bars(summary)
    plot_fel(all_data)
    write_report(summary, blocks)

    print(f"Finished MD core analysis figures and tables under {OUT}")


if __name__ == "__main__":
    main()
