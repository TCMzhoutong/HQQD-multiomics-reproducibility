def read_xvg(path: Path) -> pd.DataFrame:
    rows: list[list[float]] = []
    for line in path.read_text(errors="ignore").splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "@")):
            continue
        try:
            rows.append([float(x) for x in s.split()])
        except ValueError:
            continue
    if not rows:
        raise ValueError(f"No numeric XVG rows in {path}")
    df = pd.DataFrame(rows)
    if df.shape[1] < 2:
        raise ValueError(f"Expected at least two columns in {path}")
    return df


def metric_series(sys_info: SystemInfo, metric: str) -> pd.DataFrame:
    path = SYSTEMS_DIR / sys_info.pair_id / "03_analysis" / METRICS[metric]["file"]
    df = read_xvg(path)
    value_col = 1
    x = df.iloc[:, 0].astype(float).copy()
    if METRICS[metric]["kind"] == "time" and float(x.max()) > 1000.0:
        x = x / 1000.0
    return pd.DataFrame({"x": x, "value": df.iloc[:, value_col]})


def rolling_mean(y: pd.Series, x: pd.Series, window_ns: float = 1.0) -> pd.Series:
    if len(x) < 3:
        return y
    dt = float(np.nanmedian(np.diff(x)))
    if not np.isfinite(dt) or dt <= 0:
        return y
    window = max(1, int(round(window_ns / dt)))
    return y.rolling(window=window, center=True, min_periods=max(1, window // 5)).mean()


def ci95_from_blocks(values: np.ndarray) -> tuple[float, float, float, float]:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if len(values) == 0:
        return (np.nan, np.nan, np.nan, np.nan)
    mean = float(np.mean(values))
    sd = float(np.std(values, ddof=1)) if len(values) > 1 else 0.0
    sem = float(sd / math.sqrt(len(values))) if len(values) > 0 else np.nan
    if len(values) > 1:
        mult = float(student_t.ppf(0.975, len(values) - 1)) if student_t is not None else 1.96
        ci = mult * sem
    else:
        ci = np.nan
    return mean, sd, sem, ci


def full_and_block_stats(sys_info: SystemInfo, metric: str, data: pd.DataFrame) -> tuple[dict, list[dict]]:
    time = data["x"].to_numpy()
    values = data["value"].to_numpy()

    full = values[np.isfinite(values)]
    final = data[(data["x"] >= 80.0) & (data["x"] <= 100.0)]["value"].to_numpy()
    full_mean = float(np.nanmean(full))
    full_sd = float(np.nanstd(full, ddof=1)) if len(full) > 1 else 0.0

    blocks = []
    block_means = []
    for start in np.arange(80.0, 100.0, 5.0):
        end = start + 5.0
        subset = data[(data["x"] >= start) & (data["x"] < end)]["value"].to_numpy()
        subset = subset[np.isfinite(subset)]
        if len(subset):
            bmean = float(np.mean(subset))
            bsd = float(np.std(subset, ddof=1)) if len(subset) > 1 else 0.0
            block_means.append(bmean)
        else:
            bmean = np.nan
            bsd = np.nan
        blocks.append(
            {
                "pair_id": sys_info.pair_id,
                "system": sys_info.label,
                "protein": sys_info.protein,
                "ligand": sys_info.ligand,
                "metric": metric,
                "block_start_ns": start,
                "block_end_ns": end,
                "n_frames": int(len(subset)),
                "mean": bmean,
                "sd": bsd,
            }
        )

    final_mean, final_block_sd, final_sem, final_ci95 = ci95_from_blocks(np.asarray(block_means))
    return (
        {
            "pair_id": sys_info.pair_id,
            "system": sys_info.label,
            "protein": sys_info.protein,
            "ligand": sys_info.ligand,
            "metric": metric,
            "n_frames_total": int(len(full)),
            "full_0_100ns_mean": full_mean,
            "full_0_100ns_sd": full_sd,
            "final_80_100ns_frame_mean": float(np.nanmean(final)) if len(final) else np.nan,
            "final_80_100ns_block_mean": final_mean,
            "final_80_100ns_block_sd": final_block_sd,
            "final_80_100ns_block_sem": final_sem,
            "final_80_100ns_block_95ci": final_ci95,
            "n_blocks": int(np.sum(np.isfinite(block_means))),
            "block_size_ns": 5.0,
        },
        blocks,
    )


def clean_axis(ax: plt.Axes) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.grid(True, color="#E6E8EB", linewidth=0.55, alpha=0.9)
    ax.set_axisbelow(True)


def save_figure(fig: plt.Figure, out_stem: Path) -> None:
    out_stem.parent.mkdir(parents=True, exist_ok=True)
    for ext in [".png", ".svg", ".pdf"]:
        fig.savefig(out_stem.with_suffix(ext), bbox_inches="tight")


def plot_core_timeseries(all_data: dict[tuple[str, str], pd.DataFrame]) -> None:
    metrics = ["complex_rmsd", "protein_rmsd", "ligand_rmsd", "rg", "sasa", "hbond"]
    fig, axes = plt.subplots(3, 2, figsize=(7.2, 7.6), sharex=True)
    axes = axes.ravel()
    for ax, metric in zip(axes, metrics):
        for sys_info in SYSTEMS:
            data = all_data[(sys_info.pair_id, metric)]
            smooth = rolling_mean(data["value"], data["x"], 1.0)
            ax.plot(data["x"], smooth, color=sys_info.color, lw=1.45, label=sys_info.label)
        ax.set_title(METRICS[metric]["title"], pad=5)
        ax.set_ylabel(METRICS[metric]["ylabel"])
        clean_axis(ax)
        if metric == "hbond":
            ax.yaxis.set_major_locator(MaxNLocator(integer=True))
    for ax in axes[-2:]:
        ax.set_xlabel("Time (ns)")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=2, frameon=False, bbox_to_anchor=(0.5, -0.01))
    fig.subplots_adjust(hspace=0.34, wspace=0.28, bottom=0.15)
    save_figure(fig, OUT / "04_figures" / "01_core_timeseries_1ns_rolling_mean")
    plt.close(fig)


